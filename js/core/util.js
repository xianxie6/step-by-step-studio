function chain(stops, t) {
  if (t <= stops[0][0]) return stops[0][1];
  for (let i = 1; i < stops.length; i++) if (t <= stops[i][0]) {
    const [t0, c0] = stops[i - 1], [t1, c1] = stops[i];
    return mixc(c0, c1, (t - t0) / (t1 - t0));
  }
  return stops[stops.length - 1][1];
}
